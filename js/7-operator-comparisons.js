/**
 * Operator Comparison (Perbandingan) :
 * -. Sama Dengan (== / ===)
 * -. Tidak Sama Dengan (!= / !==)
 * -. Lebih Besar (>)
 * -. Lebih Besar dan Sama Dengan (>=)
 * -. Lebih Kecil(<)
 * -. Lebih Kecil dan Sama Dengan (<=)
 */

console.log(10 < 5);
console.log(10 > 5);
console.log(10 === 5);
console.log(10 !== 5);

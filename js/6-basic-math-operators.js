// Operator Aritmatika :
/**
 * -. Penjumlahan / Concatenation (+)
 * -. Pengurangan (-)
 * -. Perkalian (*)
 * -. Perkalian (/)
 * -. Perpangkatan (**)
 * -. Sisa Bagi/Modulus (%)
 */

console.log(2 + 5);
console.log(2 - 5);
console.log(2 * 5);
console.log(2 / 5);
console.log(2 ** 5);
console.log(2 % 5);

const nama = 'Dicky';

console.log('Halo Saya Adalah Mentor ' + nama);
console.log(`Halo Saya Adalah Mentor ${nama}`);

// Increment vs Decrement
let i = 5;

console.log(i++);
console.log(i++);

console.log(++i);

let j = 10;

console.log(j++);
console.log(j);

// Math Object
/**
 * Math.round() → pembulatan normal
 * Math.floor() → ke bawah
 * Math.ceil()  → ke atas
 * Math.sqrt()  → akar
 * Math.abs()   → absolut
 * Math.random()→ random 0-1
 * Math.max()   → nilai terbesar
 * Math.min()   → nilai terkecil
 * Math.PI      → konstanta π
 */

console.log(Math.ceil(3.1));
console.log(Math.round(3.4));
console.log(Math.sqrt(4));
console.log(Math.abs(-10));
console.log(Math.random());
